import { describe, it, expect } from 'vitest'
import { Context } from '@deepseek-ai/cordis'
import { defineFeature, FeatureError, FeatureRuntime } from '../src/index.ts'
import type { FeatureEnvironment, FeaturePlugin } from '../src/types.ts'

const feature = (id: string, execute: FeaturePlugin['execute'] = () => id, depends: string[] = []) => defineFeature({id,capability:id,title:id,depends,execute})

describe('one feature per real Cordis plugin', () => {
  it('rejects multiple-capability descriptors and duplicate identities', () => {
    expect(() => defineFeature({...feature('test.one'), capabilities:['a','b']} as any)).toThrow(FeatureError)
    expect(() => defineFeature({...feature('test.one'), capability:'test.two'})).toThrow(FeatureError)
    const runtime = new FeatureRuntime()
    runtime.register(feature('test.one'))
    expect(() => runtime.register(feature('test.one'))).toThrow('已注册')
  })
  it('keeps synchronous operations synchronous', async () => {
    const runtime = new FeatureRuntime()
    runtime.register(feature('test.list',()=>['a','b']))
    await runtime.start()
    expect(runtime.call('test.list')).toEqual(['a','b'])
    expect(runtime.get('test.list')?.activeCalls).toBe(0)
    await runtime.dispose()
  })
  it('keeps a missing dependency blocked instead of an empty success', async () => {
    const runtime = new FeatureRuntime()
    runtime.register(feature('test.child',()=>[],['test.missing']))
    await runtime.start()
    expect(runtime.get('test.child')?.status).toBe('blocked')
    expect(()=>runtime.call('test.child')).toThrow(FeatureError)
    await runtime.dispose()
  })
  it('reports circular dependencies without hanging', async () => {
    const runtime = new FeatureRuntime()
    runtime.register(feature('test.a',()=>1,['test.b']))
    runtime.register(feature('test.b',()=>2,['test.a']))
    await runtime.start()
    expect(runtime.has('test.a')).toBe(false)
    expect(runtime.list().some(item=>item.error?.includes('循环'))).toBe(true)
    await runtime.dispose()
  })
  it('provides an independent fiber and cleanup for each sibling', async () => {
    const ctx = new Context()
    const runtime = new FeatureRuntime(ctx)
    let a=0, b=0
    runtime.register({...feature('test.a'),setup:env=>env.onDispose(()=>{a++})})
    runtime.register({...feature('test.b'),setup:env=>env.onDispose(()=>{b++})})
    await runtime.start()
    expect(ctx.registry.size).toBe(2)
    await runtime.disable('test.a')
    expect(a).toBe(1)
    expect(b).toBe(0)
    expect(runtime.has('test.a')).toBe(false)
    expect(runtime.call('test.b')).toBe('test.b')
    await runtime.dispose()
    expect(a).toBe(1)
    expect(b).toBe(1)
  })
  it('only blocks required downstreams; optional peers stay enabled', async () => {
    const runtime = new FeatureRuntime()
    runtime.register(feature('test.root'))
    runtime.register(feature('test.a',()=>1,['test.root']))
    runtime.register(feature('test.b',()=>2,['test.root']))
    runtime.register(feature('test.child',()=>3,['test.a']))
    runtime.register({...feature('test.optional'),optionalDepends:['test.a']})
    await runtime.start()
    await runtime.disable('test.a')
    expect(runtime.get('test.child')?.status).toBe('blocked')
    expect(runtime.has('test.b')).toBe(true)
    expect(runtime.has('test.root')).toBe(true)
    expect(runtime.has('test.optional')).toBe(true)
    await runtime.enable('test.a')
    expect(runtime.has('test.child')).toBe(true)
    await runtime.disable('test.b')
    await runtime.disable('test.root')
    await runtime.enable('test.root')
    expect(runtime.has('test.a')).toBe(true)
    expect(runtime.has('test.b')).toBe(false)
    await runtime.dispose()
  })
  it('applies a second start configuration to already enabled features', async () => {
    const runtime = new FeatureRuntime()
    runtime.register(feature('test.a'))
    runtime.register(feature('test.b'))
    await runtime.start()
    await runtime.start({disabled:['test.b']})
    expect(runtime.has('test.a')).toBe(true)
    expect(runtime.has('test.b')).toBe(false)
    expect(()=>runtime.call('test.b')).toThrow(FeatureError)
    await runtime.start()
    expect(runtime.has('test.b')).toBe(true)
    await runtime.dispose()
  })
})

describe('declaration and lifecycle regression cases', () => {
  it('prevents context.features and context.root.features from bypassing env.use', async () => {
    const runtime = new FeatureRuntime()
    runtime.register(feature('test.target',()=>42))
    runtime.register(feature('test.attacker',(_input,env)=>env.context.features.call('test.target')))
    runtime.register(feature('test.root-attacker',(_input,env)=>env.context.root.features.call('test.target')))
    runtime.register(feature('test.reflect-attacker',(_input,env)=>env.context.reflect.get('features')))
    await runtime.start()
    expect(()=>runtime.call('test.attacker')).toThrow('没有声明依赖')
    expect(()=>runtime.call('test.root-attacker')).toThrow('没有声明依赖')
    expect(()=>runtime.call('test.reflect-attacker')).toThrow('不能直接访问')
    await runtime.dispose()
  })
  it('prevents a captured facade from running after its owning feature unloads', async () => {
    const runtime = new FeatureRuntime()
    let captured: (()=>unknown) | undefined
    runtime.project('example',{run:{feature:'test.target'}})
    runtime.register(feature('test.target',()=>42))
    runtime.register(feature('test.owner',(_input,env)=>{captured=(env.context as any).example.run;return captured?.()},['test.target']))
    await runtime.start()
    expect(runtime.call('test.owner')).toBe(42)
    await runtime.disable('test.owner')
    expect(()=>captured?.()).toThrow('取消')
    expect(runtime.call('test.target')).toBe(42)
    await runtime.dispose()
  })
  it('aborts a hung async operation, settles its lease and disposes exactly once', async () => {
    const runtime = new FeatureRuntime()
    let seenSignal: AbortSignal | undefined
    let cleanup=0
    runtime.register(feature('test.slow',(_input,env)=>{seenSignal=env.signal;env.onDispose(()=>{cleanup++});return new Promise(()=>{})}))
    await runtime.start()
    const running=runtime.call<Promise<unknown>>('test.slow').catch(error=>error)
    expect(runtime.get('test.slow')?.activeCalls).toBe(1)
    await runtime.disable('test.slow')
    const error=await running
    expect(error.code).toBe('PLUGIN_CANCELLED')
    expect(seenSignal?.aborted).toBe(true)
    expect(runtime.get('test.slow')?.activeCalls).toBe(0)
    expect(cleanup).toBe(1)
    await runtime.dispose()
    expect(cleanup).toBe(1)
  })
  it('synchronises externally disposed Cordis scopes', async () => {
    const ctx=new Context()
    const runtime=new FeatureRuntime(ctx)
    let disposed=0
    runtime.register({...feature('test.a'),setup:env=>env.onDispose(()=>{disposed++})})
    await runtime.start()
    const fiber=[...ctx.registry.values()].flatMap(record=>[...record.fibers])[0]
    expect(fiber).toBeDefined()
    await fiber!.dispose()
    expect(runtime.has('test.a')).toBe(false)
    expect(runtime.get('test.a')?.status).not.toBe('enabled')
    await runtime.enable('test.a')
    expect(runtime.call('test.a')).toBe('test.a')
    await runtime.dispose()
    expect(disposed).toBe(2)
  })
  it('does not keep an enabled status after root-context shutdown', async () => {
    const ctx=new Context()
    const runtime=new FeatureRuntime(ctx)
    runtime.register(feature('test.a'))
    await runtime.start()
    await ctx.fiber.dispose()
    expect(runtime.has('test.a')).toBe(false)
    expect(runtime.get('test.a')?.status).not.toBe('enabled')
    expect(()=>runtime.call('test.a')).toThrow(FeatureError)
    await runtime.dispose()
  })
  it('shared implementation state does not retain the first feature scope', async () => {
    class Repository { count=0; constructor(readonly context: Context) {} next(id:string) { this.count++; return this.context.features.call(id) } }
    const runtime=new FeatureRuntime()
    runtime.register(feature('test.target-a',()=>1))
    runtime.register(feature('test.target-b',()=>2))
    const run=(id:string)=>feature(id,(_input,env)=>env.state('repo',()=>new Repository(env.context)).next(id==='test.a'?'test.target-a':'test.target-b'),[id==='test.a'?'test.target-a':'test.target-b'])
    runtime.register(run('test.a'))
    runtime.register(run('test.b'))
    await runtime.start()
    expect(runtime.call('test.a')).toBe(1)
    await runtime.disable('test.a')
    expect(runtime.call('test.b')).toBe(2)
    expect(runtime.state('repo',()=>new Repository(new Context())).count).toBe(2)
    await runtime.dispose()
  })
  it('maintains a stable external-store snapshot between lifecycle changes', async () => {
    const runtime=new FeatureRuntime()
    runtime.register(feature('test.a'))
    await runtime.start()
    const snapshot=runtime.snapshot()
    runtime.call('test.a')
    expect(runtime.snapshot()).toBe(snapshot)
    await runtime.disable('test.a')
    expect(runtime.snapshot()).not.toBe(snapshot)
    await runtime.dispose()
  })
})
