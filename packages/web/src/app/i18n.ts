/** Interpolate {name} placeholders; missing params are left untouched. */
export function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match,
  )
}

export type TranslateParams = Record<string, string | number>

export type Translator = (key: string, params?: TranslateParams) => string

/** Build a translator bound to one locale (pure; used by tests and the shell). */
export function createTranslator(locale: Locale): Translator {
  const primary = DICTIONARIES[locale] ?? DICTIONARIES['zh-CN']
  return (key, params) => {
    const value = primary[key] ?? zh[key] ?? key
    return interpolate(value, params)
  }
}

/** Keys present in the dictionary; handy for tests and the shortcut sheet. */
export function dictionaryKeys(locale: Locale): string[] {
  return Object.keys(DICTIONARIES[locale] ?? {})
}

/** Normalise an unknown locale tag (from settings) into a supported one. */
export function normalizeLocale(value: string | undefined | null): Locale {
  if (!value) return 'zh-CN'
  if (value.toLowerCase().startsWith('en')) return 'en-US'
  return 'zh-CN'
}

/** Locale used when a key is missing from the active dictionary. */
export function fallbackLocale(_locale: Locale): Locale {
  return 'zh-CN'
}